"""Generate novig-cheatsheet.md + contracts.json from the official OpenAPI 3.1 spec,
annotating which endpoints were verified live (public, unauthenticated)."""
import json, re, os, glob
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d=json.load(open(f'{ROOT}/research/openapi-v3.json'))
S=d['components']['schemas']
LIVE=json.load(open(f'{ROOT}/research/live_verified.json'))  # public path -> example
AUTH=json.load(open(f'{ROOT}/research/live_authed.json'))     # signed path -> real paper response
ERR={k:v for k,v in AUTH.items() if isinstance(v,dict) and v.get('ok') is False}
for k,v in AUTH.items():
    if k not in ERR: LIVE[k]=v

def ref(r): return S[r.split('/')[-1]]
def tname(s):
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'allOf' in s: return ' & '.join(tname(x) for x in s['allOf'])
    if 'oneOf' in s or 'anyOf' in s: return ' | '.join(tname(x) for x in s.get('oneOf',s.get('anyOf')))
    if 'enum' in s: return 'enum('+', '.join(map(str,s['enum'][:12]))+(' …' if len(s['enum'])>12 else '')+')'
    t=s.get('type','any')
    if isinstance(t,list): t='|'.join(t)
    if t=='array' or 'items' in s: return tname(s.get('items',{}))+'[]'
    if 'const' in s: return f'const {json.dumps(s["const"])}'
    f=s.get('format'); return f'{t}<{f}>' if f else t

def fields(s, pre='', depth=0, seen=()):
    """yield (path, type, required, desc)"""
    out=[]
    if depth>5: return out
    if '$ref' in s:
        n=s['$ref'].split('/')[-1]
        if n in seen: return out
        return fields(ref(s['$ref']),pre,depth,seen+(n,))
    for k in ('allOf',):
        if k in s:
            for x in s[k]: out+=fields(x,pre,depth,seen)
    for k in ('oneOf','anyOf'):
        if k in s:
            for x in s[k]:
                if x.get('type')=='null': continue
                out+=fields(x,pre,depth,seen)
    if 'items' in s and s.get('type')!='object':
        return out+fields(s['items'],pre+'[]',depth+1,seen)
    req=set(s.get('required',[]))
    for k,v in (s.get('properties') or {}).items():
        p=f'{pre}.{k}' if pre else k
        desc=(v.get('description') or '')
        if '$ref' in v and not desc: desc=(ref(v['$ref']).get('description') or '')
        out.append((p,tname(v),k in req,desc.split('\n')[0][:140]))
        out+=fields(v,p,depth+1,seen)
    ap=s.get('additionalProperties')
    if isinstance(ap,dict):
        out.append((pre+'{key}',tname(ap),False,'map value'))
        out+=fields(ap,pre+'{key}',depth+1,seen)
    # dedupe
    r=[];sn=set()
    for f in out:
        if f[0] not in sn: sn.add(f[0]); r.append(f)
    return r

def tbl(rows):
    if not rows: return '_(no fields / scalar)_\n'
    s='| Field | Type | Req | Notes |\n|---|---|---|---|\n'
    for p,t,r,dd in rows: s+=f"| `{p}` | `{t}` | {'✓' if r else ''} | {dd.replace('|','/')} |\n"
    return s

def kv(desc,key):
    m=re.search(r'\*\*'+key+r'\*\*\s*\|\s*([^\n]*?)\s*\|\n',desc or '')
    return re.sub(r'<[^>]+>','',m.group(1)).strip() if m else ''

ops=[];contracts={}
for p,v in d['paths'].items():
    for m,o in v.items():
        if m not in('get','post','delete','put','patch'): continue
        ops.append((p,m,o))
order=['public','types','catalog','history','exchange','time','echo','limits','keys','account','orders','portfolio','ws']
ops.sort(key=lambda x:(next((i for i,k in enumerate(order) if x[0].startswith('/v3/'+k)),99),x[0],x[1]))

md=["# Novig API v3 — cheatsheet (pinned contracts)\n",
"Generated by `tools/gen_cheatsheet.py` from Novig's official OpenAPI 3.1 document (`research/openapi-v3.json`, fetched from https://docs.novig.com/api-reference/spec-files/openapi-v3.json on 2026-10-22) plus live calls.\n",
"**Hosts:** Paper `https://api.paper.novig.com` (play money, $10k start, no location check) · Production `https://api.novig.com`. WebSocket same host, `wss://…/v3/ws`. Keys are per-environment.\n",
"**Auth (signed routes):** headers `Novig-Key-Id` (key UUID), `Novig-Timestamp` (unix ms, ±30 s), `Novig-Signature` (standard padded base64 of the NOVIG-V3 signature, Ed25519 or P-256). See `research/api_signing.md`. Key kinds: *management* (opens/funds subaccounts, cannot trade), *trading*, *trading::read*. Any key reads catalog/types/history.\n",
"**Public (no key):** `/v3/public/...` mirrors of catalog + types. Plus daily anonymized CSVs at `https://data.novig.com/reporting/trade-data/` (see bottom).\n",
"**Units:** price = probability string, 3 places (e.g. 0.665 sent as a string); qty = whole contracts; **a winning contract pays 1 cent** (cost = P*N*1c, so 110 @ 0.665 = $0.73150); balances = decimal strings, 5 places; timestamps int64 unix **ms**. The book holds **bids only**: ask on outcome A = 1 - best bid on outcome B. Per-wallet responses (`{key}` rows) = a management key gets a map keyed by subaccount keyId.\n",
"**Legend:** ✅ LIVE-VERIFIED (called 2026-10-22, real response shape pinned below) · 📄 FROM DOCS, UNVERIFIED (needs a key; schema straight from OpenAPI).\n",
"## Index\n","| # | Method | Path | Auth | Status | Summary |","|---|---|---|---|---|---|"]
body=[]
for i,(p,m,o) in enumerate(ops,1):
    auth='none' if not o.get('security') else (kv(o.get('description'),'Key') or 'signed')
    live=p in LIVE and m in ('get',) or (p=='/v3/echo' and m=='post')
    err=ERR.get(p) if m=='get' else None
    st='✅ live' if live else ('⚠️ called: '+err.get('code','') if err else '📄 docs')
    md.append(f"| {i} | {m.upper()} | `{p}` | {auth} | {st} | {o.get('summary','')} |")
    b=[f"\n### {i}. `{m.upper()} {p}` — {o.get('summary','')}\n",
       f"- **Auth:** {auth} · **Throttle:** {kv(o.get('description'),'Throttle') or '-'} · **Cost:** {kv(o.get('description'),'Cost') or '-'} · **Idempotent:** {kv(o.get('description'),'Idempotent') or '-'}",
       f"- **Status:** {('✅ LIVE-VERIFIED (' + ('public, unauthenticated' if '/public/' in p else 'signed, PAPER management key') + ')') if live else ('⚠️ CALLED LIVE, returned `'+json.dumps({k:v for k,v in err.items() if k!='ok'})+'` (shape from docs)' if err else '📄 FROM DOCS, UNVERIFIED')}"+f" · operationId `{o.get('operationId')}`"]
    tail=re.sub(r'\|[^\n]*\|\n?','',o.get('description') or '').strip()
    if tail: b.append('\n> '+tail.replace('\n','\n> ')+'\n')
    params=o.get('parameters',[])+v.get('parameters',[])
    if params:
        b.append('\n**Parameters**\n\n| Name | In | Type | Req | Notes |\n|---|---|---|---|---|')
        for pr in params:
            if '$ref' in pr: pr=d['components']['parameters'][pr['$ref'].split('/')[-1]]
            b.append(f"| `{pr['name']}` | {pr['in']} | `{tname(pr.get('schema',{}))}` | {'✓' if pr.get('required') else ''} | {(pr.get('description') or '').splitlines()[0][:140] if pr.get('description') else ''} |")
    rq=o.get('requestBody',{}).get('content',{}).get('application/json')
    c={'method':m.upper(),'path':p,'auth':auth,'live':live,'request':[],'responses':{}}
    if rq:
        rows=fields(rq['schema']); c['request']=[r[0] for r in rows]
        b.append(f"\n**Request body** `{tname(rq['schema'])}`\n\n"+tbl(rows))
        if 'example' in rq: b.append('```json\n'+json.dumps(rq['example'],indent=1)+'\n```')
    for code,r in o.get('responses',{}).items():
        ct=(r.get('content') or {}).get('application/json')
        if not ct:
            b.append(f"\n**{code}** — {r.get('description','')}"); continue
        if code.startswith('2'):
            rows=fields(ct['schema']); c['responses'][code]=[x[0] for x in rows]
            b.append(f"\n**Response {code}** `{tname(ct['schema'])}` — {r.get('description','')}\n\n"+tbl(rows))
            ex=LIVE.get(p) if live else ct.get('example')
            if ex is not None:
                b.append(('Live example (truncated):' if live else 'Doc example:')+'\n```json\n'+json.dumps(ex,indent=1)[:2500]+'\n```')
        else:
            b.append(f"- **{code}** {r.get('description','')} e.g. `{json.dumps(ct.get('example'))}`")
    contracts[f'{m.upper()} {p}']=c
    body.append('\n'.join(b))
md+=body
md.append(open(f'{ROOT}/research/cheatsheet_tail.md').read())
open(f'{ROOT}/novig-cheatsheet.md','w').write('\n'.join(md))
json.dump(contracts,open(f'{ROOT}/contracts.json','w'),indent=1)
print(len(ops),'ops', sum(c['live'] for c in contracts.values()),'live')
